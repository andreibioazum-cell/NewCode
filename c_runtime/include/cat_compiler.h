/*
 * cat_compiler.h - Компилятор проектов NewCode: проект Catrobat -> C -> машинный код.
 *
 * В отличие от интерпретатора (cat_interpreter.h), компилятор не исполняет
 * брикки по одному, а ПОЛНОСТЬЮ транслирует проект в исходник на C,
 * который затем компилируется обычным C-компилятором (cc) в нативный
 * исполняемый файл. Никакого байт-кода, никакой виртуальной машины,
 * никакой сборки мусора: значения живут на стеке, а C-блоки работают
 * с настоящей памятью через явные malloc/free.
 */
#ifndef CAT_COMPILER_H
#define CAT_COMPILER_H

#include "cat_project.h"

/* Скомпилировать проект в исходник на C. Возвращает cat_malloc'нутую
   строку (освобождается cat_free). */
char *cat_compile_to_c(CatProject *p);

/* Текст мини-рантайма nc_rt.h: его нужно сохранить рядом со
   сгенерированным .c-файлом перед компиляцией. */
const char *cat_compiler_runtime_header(void);

#endif /* CAT_COMPILER_H */
